global.window = globalThis;
require('../public/edd/core.js');
const E = globalThis.EDD;
const assert = require('assert');
E.db.config.set('general',{id:'general',d:{}});
const p = {id:'p1', d:{nombre:'X', fecha_ingreso:'2026-05-25'}};
const mk = (c)=>({id:'2026-10|p1', d:{periodo_id:'2026-10', items:c.map((x,i)=>({id:'m'+i,nombre:'M'+i,peso:25,cumplimiento:x}))}});
let r = E.calc.metricos(mk([100,100,100,0]), p);
assert.strictEqual(r.calculado, 1125); assert.strictEqual(r.final, 1125); assert.strictEqual(r.suma, 100);
r = E.calc.metricos(mk([100,100,100,50]), p);
assert.strictEqual(r.calculado, 1312.5);
const g = {id:'p2', d:{nombre:'G', fecha_ingreso:'2026-09-22'}};
assert.deepStrictEqual(E.calc.periodosGarantiaPropuestos(g), ['2026-09','2026-10']);
r = E.calc.metricos(mk([0,0,100,0]), g);
assert.strictEqual(r.calculado, 375); assert.strictEqual(r.minimo, 1125); assert.strictEqual(r.final, 1125); assert.strictEqual(r.garantiaAplicada, 750);
assert.ok(r.garantia.requiereConfirmar);
E.db.config.set('general',{id:'general',d:{garantia_regla:'primer_mes_completo'}});
assert.deepStrictEqual(E.calc.periodosGarantiaPropuestos(g), ['2026-10','2026-11']);
assert.strictEqual(E.periodo.serialExcel('2026-10'), 46296);
assert.strictEqual(E.periodo.hoja('2026-10'),'Octubre-2026'); assert.strictEqual(E.periodo.corto('2026-10'),'oct-26');
assert.ok(!E.calc.garantia(p,'2026-10').requiereConfirmar);
assert.strictEqual(E.calc.base(null,{d:{base_comision:1250}}), 1250);
console.log('calc OK');
